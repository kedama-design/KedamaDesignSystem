/**
 * Kedama Design System — プリミティブカラートークン
 *
 * OKLCH 色空間で生成。HEX 値は OKLCH → sRGB 変換後の値。
 *
 * 設計方針:
 * - OKLCH ベースの知覚的に均一なスケール
 * - **明度カーブは全パレット共通**（段番号が L を決める）
 *     25:97.6 / 50:95 / 100:90 / 200:80 / 300:70 / 400:60
 *     500:50 / 600:40 / 700:30 / 800:20 / 900:10
 *   これにより「同じ段＝同じ明るさ」が保証される。
 * - WCAG 2.2 AA 全ペア検証済み（原則2: Accessible）
 * - ニュートラルは暖色系（birch / 白樺）
 * - 純白 #FFFFFF / 純黒 #000000 は不使用。最明色は birch/25、最暗色は birch/900。
 *
 * ─── 色相の出典（2026-07-31 改定）─────────────────────
 *
 * 改定前は primary 151.6° / success 114.5° と**どちらも緑**で、Badge 上で
 * ΔE 0.042（subtle 背景では 0.023）と実質判別できなかった。
 * 色相環も 55〜152° に4色が密集し、逆側 136° が空白という偏りがあった。
 *
 * | パレット | 色相   | 出典                             |
 * |----------|--------|----------------------------------|
 * | primary  | 159.3° | Starbucks Green Accent `#00754A` |
 * | success  | 145.4° | Notion green `#1aae39`           |
 * | warning  |  84.0° | Starbucks yellow `#fbbc05`       |
 * | danger   |  29.6° | Starbucks red `#c82014`          |
 * | info     | 254.3° | Notion blue `#0075de`            |
 * | birch    | 暖色   | Kedama 独自（変更なし）          |
 *
 * **重要**: primary と success は色相が 13.9° しか離れていない（どちらも緑）。
 * 両者の判別は**色相ではなく参照する段の明度差**で確保している。
 * `accent.primary` が 600 番、`status.success` 系が 300 番を指すことで
 * ΔE 0.321（D型でも 0.312）を得ている。同じ段どうしでは 0.033 しかない。
 *
 * この対応関係を崩す（例: success を 600 番に戻す）と判別不能に戻るため、
 * 段の割り当てを変えるときは必ずコントラストテストを再実行すること。
 * 詳細は docs/phase-a1-token-decisions.md、検証は tests/contrastCases.ts。
 *
 * 恒久的なブランド定義は安定稼働後に行う予定で、本パレットはその暫定値。
 *
 * Figma Variables との対応:
 *   Collection: "Primitives" > Group: "color"
 *   例: color/primary/600, color/birch/25
 */

